package gg.umbra.wrapper.impl;

import gg.umbra.mapping.mappings.MMainWindow;
import gg.umbra.wrapper.Wrapper;

public class MainWindow
extends Wrapper {
    public MainWindow(Object object) {
        super(object);
    }

    public float i() {
        return MMainWindow.E(MainWindow.umbraInstance.getMappingsMapperCompat().DU, this.I);
    }

    public float q() {
        return MMainWindow.y(MainWindow.umbraInstance.getMappingsMapperCompat().DU, this.I);
    }

    public int x() {
        return MMainWindow.T(MainWindow.umbraInstance.getMappingsMapperCompat().DU, this.I);
    }

    public int o() {
        return MMainWindow.C(MainWindow.umbraInstance.getMappingsMapperCompat().DU, this.I);
    }

    public float r() {
        return MMainWindow.e(MainWindow.umbraInstance.getMappingsMapperCompat().DU, this.I);
    }

    public float A() {
        return MMainWindow.W(MainWindow.umbraInstance.getMappingsMapperCompat().DU, this.I);
    }
}

